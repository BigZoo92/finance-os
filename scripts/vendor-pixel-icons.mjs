  'at',
  'bank',
  'bell',
  'branch',
  'chart-line',
  'chart-network',
  'check',
  'check-list',
  'chevron-down',
  'chevron-up',
  'clock',
  'cog',
  'coins',
  'command',
  'comment',
  'download',
  'ellipses-horizontal',
  'exclamation-triangle',
  'external-link',
  'eye',
  'filter',
  'flag',
  'graduation-cap',
  'grid',
  'hashtag',
  'home',
  'link',
  'lock',
  'moon',
  'newspaper',
  'notebook',
  'pause',
  'play',
  'plane-departure',
  'question',
  'receipt',
  'refresh',
  'robot',
  'search',
  'shuffle',
