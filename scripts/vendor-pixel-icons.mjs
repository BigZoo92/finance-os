#!/usr/bin/env node
/**
 * Vendors the curated Finance-OS Pixel Icon set into `packages/ui/src/icons/pixel`.
 *
 * Upstream artwork: HackerNoon Pixel Icon Library (`@hackernoon/pixel-icon-library`),
 * the same 24px-grid catalogue published as "Pixel Icon" on https://www.shadcn.io/icons/pixel.
 * The `.svg` assets are CC BY 4.0; attribution lives in `docs/third-party-notices.md`.
 *
 * This is build-time tooling only: the generated components have no runtime dependency
 * on the upstream package, and the package is never added to the workspace manifest.
 *
 * Usage:
 *   node scripts/vendor-pixel-icons.mjs            # regenerate from a cached tarball
 *   node scripts/vendor-pixel-icons.mjs --download # fetch the tarball first (needs network)
 *
 * To add an icon: add its upstream name to ICONS below, rerun, then `pnpm lint`.
 */

import { execFileSync } from 'node:child_process'
import { mkdtempSync, readdirSync } from 'node:fs'
import { mkdir, readdir, readFile, unlink, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = join(REPO_ROOT, 'packages', 'ui', 'src', 'icons', 'pixel')
const UPSTREAM_PACKAGE = '@hackernoon/pixel-icon-library'
const UPSTREAM_VARIANT = 'regular'

/**
 * The curated set. Every entry must have a real consumer in the product.
 * Keep this list small: it is the whole point of vendoring instead of depending.
 */
